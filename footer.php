        function askPresetQuestion(key) {
            const currentLang = localStorage.getItem('ep_lang') || 'th';
            const textTh = {
                admissions: "ข้อมูลการรับสมัครเรียน",
                fees: "ค่าเทอมและค่าธรรมเนียม",
                curriculum: "หลักสูตรและวิชาเรียน",
                contact: "ติดต่อสำนักงาน EP"
            };
            const textEn = {
                admissions: "Admissions Info",
                fees: "Tuition & Fees",
                curriculum: "Curriculum Info",
                contact: "Contact EP Office"
            };

            const userQuestion = currentLang === 'en' ? textEn[key] : textTh[key];
            const answer = PRESET_RESPONSES[key][currentLang];
            
            appendMessage('user', userQuestion);
            setTimeout(() => {
                appendMessage('bot', answer);
            }, 500);
        }

        function sendChatMessage() {
            const input = document.getElementById('ep-chat-input');
            if (!input || !input.value.trim()) return;

            const text = input.value.trim();
            appendMessage('user', text);
            input.value = '';

            setTimeout(() => {
                const currentLang = localStorage.getItem('ep_lang') || 'th';
                const botReply = currentLang === 'en' 
                    ? "Thank you for your message! Our administrators will get back to you shortly. You can also call us directly at 02-583-5444." 
                    : "ขอบคุณสำหรับข้อความครับ! เจ้าหน้าที่ฝ่ายโครงการจะติดต่อกลับท่านโดยเร็วที่สุด หรือท่านสามารถโทรสอบถามโดยตรงได้ที่ 02-583-5444";
                appendMessage('bot', botReply);
            }, 600);
        }

        function appendMessage(sender, text) {
            const container = document.getElementById('ep-chat-messages');
            if (!container) return;

            const msgDiv = document.createElement('div');
            msgDiv.className = "flex gap-2 " + (sender === 'user' ? 'justify-end' : 'justify-start');

            const contentHtml = text.replace(/\n/g, '<br>').replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
            
            if (sender === 'user') {
                msgDiv.innerHTML = `
                    <div class="bg-brand-500 text-white rounded-2xl rounded-tr-none p-3 shadow-sm max-w-[85%] leading-relaxed font-medium">
                        ${contentHtml}
                    </div>
                `;
            } else {
                msgDiv.innerHTML = `
                    <div class="w-7 h-7 rounded-full bg-brand-500 flex items-center justify-center text-white text-[10px] font-bold flex-shrink-0">EP</div>
                    <div class="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl rounded-tl-none p-3 shadow-sm max-w-[85%] leading-relaxed">
                        ${contentHtml}
                    </div>
                `;
            }

            container.appendChild(msgDiv);
            container.scrollTop = container.scrollHeight;
        }
